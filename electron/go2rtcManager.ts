import { app } from 'electron';
import { spawn, type ChildProcessWithoutNullStreams } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

type Go2RtcStatus = {
  running: boolean;
  binaryPath: string;
  configPath: string;
  message: string;
};

export type Go2RtcStreamConfig = {
  streamName: string;
  rtspUrl: string;
};

const GO2RTC_BASE_URL = 'http://127.0.0.1:1984';
let processRef: ChildProcessWithoutNullStreams | undefined;
let lastStatus: Go2RtcStatus | undefined;
let streamConfigs: Go2RtcStreamConfig[] = [];

function getGo2RtcBinaryPath() {
  if (app.isPackaged) {
    return path.join(process.resourcesPath, 'go2rtc', 'go2rtc.exe');
  }

  return path.join(app.getAppPath(), 'resources', 'go2rtc', 'go2rtc.exe');
}

function getGo2RtcConfigPath() {
  return path.join(app.getPath('userData'), 'go2rtc.yaml');
}

function quoteYamlValue(value: string) {
  return `'${value.replace(/'/g, "''")}'`;
}

function createConfig(streams: Go2RtcStreamConfig[]) {
  const streamLines =
    streams.length > 0
      ? streams.flatMap((stream) => [
          `  ${stream.streamName}:`,
          `    - ${quoteYamlValue(stream.rtspUrl)}`
        ])
      : ['  {}'];

  return [
    'api:',
    '  listen: "127.0.0.1:1984"',
    '  origin: "*"',
    '',
    'rtsp:',
    '  listen: "127.0.0.1:8554"',
    '',
    'webrtc:',
    '  listen: ":8555"',
    '',
    'streams:',
    ...streamLines,
    ''
  ].join('\n');
}

function writeConfigFile(configPath: string) {
  const config = [
    '# Generated by RTSP Camera Dashboard.',
    '# Do not edit while the app is running.',
    createConfig(streamConfigs)
  ].join('\n');

  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, config, 'utf8');
}

export function startGo2Rtc() {
  const binaryPath = getGo2RtcBinaryPath();
  const configPath = getGo2RtcConfigPath();

  if (processRef && !processRef.killed) {
    return lastStatus;
  }

  if (!fs.existsSync(binaryPath)) {
    lastStatus = {
      running: false,
      binaryPath,
      configPath,
      message: 'go2rtc.exe nao encontrado. Execute npm run download:go2rtc antes de empacotar.'
    };
    return lastStatus;
  }

  writeConfigFile(configPath);

  processRef = spawn(binaryPath, ['-config', configPath], {
    windowsHide: true,
    stdio: 'pipe'
  });

  processRef.once('exit', (code) => {
    processRef = undefined;
    lastStatus = {
      running: false,
      binaryPath,
      configPath,
      message: `go2rtc finalizado com codigo ${code ?? 'desconhecido'}.`
    };
  });

  processRef.stderr.on('data', (chunk) => {
    console.warn(`[go2rtc] ${chunk.toString().trim()}`);
  });

  lastStatus = {
    running: true,
    binaryPath,
    configPath,
    message: 'go2rtc iniciado pelo Electron.'
  };

  return lastStatus;
}

export function stopGo2Rtc() {
  if (processRef && !processRef.killed) {
    processRef.kill();
  }
}

function waitForExit() {
  const processToWait = processRef;

  if (!processToWait) {
    return Promise.resolve();
  }

  return new Promise<void>((resolve) => {
    processToWait.once('exit', () => resolve());
    processToWait.kill();
  });
}

export async function configureGo2RtcStreams(streams: Go2RtcStreamConfig[]) {
  const previousStreams = new Map(streamConfigs.map((stream) => [stream.streamName, stream]));
  const nextStreams = new Map(streams.map((stream) => [stream.streamName, stream]));
  streamConfigs = streams;

  if (!processRef || processRef.killed) {
    startGo2Rtc();
    await new Promise((resolve) => setTimeout(resolve, 700));
  }

  const configPath = getGo2RtcConfigPath();
  writeConfigFile(configPath);

  for (const previousStream of previousStreams.values()) {
    if (!nextStreams.has(previousStream.streamName)) {
      await removeStream(previousStream.streamName);
    }
  }

  for (const nextStream of nextStreams.values()) {
    const previousStream = previousStreams.get(nextStream.streamName);

    if (!previousStream || previousStream.rtspUrl !== nextStream.rtspUrl) {
      await upsertStream(nextStream);
    }
  }

  return getGo2RtcStatus();
}

async function upsertStream(stream: Go2RtcStreamConfig) {
  const endpoint = new URL(`${GO2RTC_BASE_URL}/api/streams`);
  endpoint.searchParams.set('name', stream.streamName);
  endpoint.searchParams.set('src', stream.rtspUrl);

  const response = await fetch(endpoint, { method: 'PUT' });

  if (!response.ok) {
    throw new Error(`go2rtc nao aceitou o stream ${stream.streamName}: ${response.status}`);
  }
}

async function removeStream(streamName: string) {
  const endpoint = new URL(`${GO2RTC_BASE_URL}/api/streams`);
  endpoint.searchParams.set('src', streamName);

  const response = await fetch(endpoint, { method: 'DELETE' });

  if (!response.ok && response.status !== 404) {
    throw new Error(`go2rtc nao removeu o stream ${streamName}: ${response.status}`);
  }
}

export function getGo2RtcStatus() {
  return (
    lastStatus ?? {
      running: false,
      binaryPath: getGo2RtcBinaryPath(),
      configPath: getGo2RtcConfigPath(),
      message: 'go2rtc ainda nao foi iniciado.'
    }
  );
}

export async function checkGo2RtcHealth() {
  try {
    const response = await fetch(`${GO2RTC_BASE_URL}/api/streams`, {
      method: 'GET',
      cache: 'no-store'
    });

    return response.ok;
  } catch {
    return false;
  }
}
